/**
 * @file hold_pid.h
 * @brief 锁位速度环 (中环): 平移速度误差 (cm/s) → 目标倾角 (°)
 *
 * 控制结构 (串级, 从外到内):
 *   位置环   (position_pid.c): 位置误差 → 目标速度 (cm/s)
 *        │
 *        ▼
 *   锁位速度环 (hold_pid.c):    平移速度误差 → 目标倾角 (°)
 *        │
 *        ▼
 *   平衡环   (balance_pid.c):   姿态误差 → 电机输出 (%)
 *
 * 为什么位置环和平衡环之间必须夹一个速度环:
 *   1) **阻尼**: 平移速度 = 位置误差的导数, 所以速度环的 P 项就是位置环的
 *      D 项 —— 而且它作用在**车真实的平移速度**上, 相位比"拿编码器轮速
 *      (300 ms 窗口) 当 D 项"对得多 (实测 300 ms 滞后 ≈ 负阻尼 →
 *      4~6 秒周期、幅度越甩越大的前后振荡)。
 *   2) **保持**: 站住不动时, 车要抗摩擦/抗轮子阻力, 必须有一个**常驻倾角**。
 *      平衡环的积分太慢, 靠它攒这个倾角要几十秒; 速度环的积分专干这件事。
 *      位置环的死区**不会**清掉这个积分 → 站得住, 也不会有死区极限环。
 *   3) **分工**: 平衡环只负责"把实际倾角跟到目标倾角", 不再和外环抢倾角。
 *
 * 反馈用**里程计速度** (odom, 60 ms 窗口), 不用编码器轮速 (300 ms 窗口):
 * 后者滞后 ~150 ms, 阻尼相位落后 → 等价负阻尼。
 *
 * 本环只在"站着不动"时运行 (balance.c 的 HOLD 模式);
 * 行走时由 speed_pid (轮速环) 给目标倾角, 两个环不同时说话。
 *
 * @author ESP32 平衡轮腿机器人
 * @date 2026-10-29
 */

#ifndef HOLD_PID_H
#define HOLD_PID_H

/* ========== 锁位速度环参数 (cm/s → °) ========== */

/* 锁位速度环的内置默认增益 (°/(cm/s)):
 * 参数表里的 hold_kp 被写成 0 时用它兜底 —— 位置保持全靠这个环,
 * 关掉它等于"推了不回位", 不该由 App 误拖滑块就废掉。
 * 取值依据见 test/pos_hold_sim.py 的离线仿真 (0.8 °/(cm/s):
 * 1 cm/s 的速度误差 → 0.8° 的前倾要求, 回位不冲、刹得住)。 */
#define HOLD_PID_KP_DEFAULT  0.8f

/* 速度误差死区 (cm/s): **只作用在 P 项上** (积分照常累加)。
 * 里程计速度的量化台阶 = 0.0155 cm/pulse ÷ 0.06 s ≈ 0.26 cm/s,
 * 死区取 0.3 cm/s ≈ 1 个台阶: 免得车为了追一个量化噪声一直歪着。
 * ⚠ 死区不能作用在积分上: 积分是"抗摩擦的常驻倾角", 一旦被死区冻住,
 *   车就站不住了 (跟 speed_pid / position_pid 踩过的坑一模一样)。 */
#define HOLD_PID_V_DEADBAND  0.3f

/* 速度误差软化过渡带 (cm/s): 死区与全响应之间线性压缩, 保证连续。 */
#define HOLD_PID_V_SOFT_BAND 0.3f

/* 目标倾角上限 (°): 位置保持时车最多歪这么多。
 * ⚠ 取 3.0 (2026-10-29 从 2.0 提上来): 原来 2° 太弱, 车被推一下之后
 *   回位力矩不足以克服电机死区 → 轮子不转 → 位置误差消不掉 (实测卡在 -2.8 cm)。
 *   3° 仍然小于走路的 4° 安全阀。 */
#define HOLD_PID_LEAN_MAX    3.0f

/* 积分状态上限 (cm): ∫(速度误差)dt 的限幅。
 * 积分项的贡献 = hold_ki × 积分值, 默认 ki=0.3 °/cm → 最多 1.5°,
 * 刚好在倾角上限之内, 不会把 P 项的余量吃光。 */
#define HOLD_PID_I_MAX       5.0f

/* 目标倾角限速 (°/s): 目标倾角一跳变, 平衡环就被迫猛纠 → 车前后摆。
 * 20 °/s: 从 -3° 摆到 +3° 用 0.3 秒 (原来 10 °/s 要 0.6 秒),
 * 回位方向反转时的滞后减半 —— 这是"回位冲过头"的一个来源。 */
#define HOLD_PID_LEAN_SLEW   20.0f

/* 目标倾角的一阶低通时间常数 (秒): 再滤一层台阶/噪声。 */
#define HOLD_PID_LEAN_LPF_TAU 0.05f

/**
 * @brief 初始化锁位速度环 (从 param 表读增益 + 清积分)
 */
void hold_pid_init(void);

/**
 * @brief 从 param 表重新读取锁位速度环增益
 */
void hold_pid_load_params(void);

/**
 * @brief 清空积分与输出整形状态
 */
void hold_pid_reset(void);

/**
 * @brief 执行一次锁位速度环运算
 * @param dt         控制周期 (秒)
 * @param v_cmps     实测平移速度 (cm/s, 前进为正): 里程计速度 (60 ms 窗口)
 * @param v_ref_cmps 目标平移速度 (cm/s, 前进为正): 位置环的输出
 * @return 目标倾角 (°, **正 = 车头往前倾**)
 */
float hold_pid_update(float dt, float v_cmps, float v_ref_cmps);

#endif // HOLD_PID_H
