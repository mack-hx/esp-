/**
 * @file speed_pid.h
 * @brief 速度环 (外环): 轮速误差 → 目标倾角 (°)
 *
 * @note  控制结构 (串级, 从外到内):
 *            速度环 (speed_pid.c): 轮速误差 → 目标倾角 (°)
 *                 │
 *                 ▼
 *            平衡环 (balance_pid.c): 姿态误差 → 电机输出 (%)
 *
 * @note  轮速约定: 全部用"**前进为正**"的轮速 (rpm)。
 *        前进 = 车头方向 (车头往下、pitch 为负 的那个方向)。
 *
 * @author ESP32 平衡轮腿机器人
 * @date 2026-10-27
 */

#ifndef SPEED_PID_H
#define SPEED_PID_H

/* ========== 速度环参数 (°, rpm) ==========
 * 全部搬到了本模块, 原来挤在 balance.h 里。 */

/* 轮速误差死区 (rpm): 必须 ≥ 编码器量化台阶, 免得车为了追一个量化噪声一直歪着
 * (慢慢往一边跑)。
 *
 * ⚠ 2026-10-26 (减速比 30 之后重算):
 *   换算公式: rpm = 脉冲数 × 60 / (窗口秒数 × 44 × gear)
 *     44 = 编码器每转脉冲数 (装在**电机轴**上), gear = 减速比 (默认 30)
 *   300ms 窗口下 1 个脉冲 = 60/(0.3 × 44 × 30) ≈ **0.15 rpm**
 *     (之前按 gear=1 算出来是 4.5 rpm, 那个数已经作废)
 *   死区取 1.0 rpm ≈ 6.6 个量化台阶: 既能滤掉量化噪声, 又不会把
 *   真实的速度误差一起吃掉。
 *   ⚠ 旧的 5.0 是按"量化台阶 4.5 rpm"定的, 换算成 0.15 rpm 之后太粗了 ——
 *   相当于把 5% 的目标速度误差直接丢掉 (目标 100 rpm 时死区 5 rpm)。
 *
 * ⚠ 这些数字**依赖 gear 参数**: 改了 gear 必须重算量化台阶。 */
#define SPD_PID_ERR_DEADBAND  1.0f

/* 走路时允许的最大倾角目标 (°): 速度环给出的目标倾角被夹在这个范围内。
 * 安全阀: 目标轮速定太高 (或电机带不动) 时, 宁可走慢, 也不能让车倾到摔。
 * ⚠ 2026-10-26: 仿真的结论 (test/bal_sim.py --walk-scan, 27 组植物参数):
 *   倾角上限 12° + spd_kp 0.15 → 车身倾角波动中位 10.7° (最大 28.9°)
 *   倾角上限 4°  + spd_kp 0.06 → 倾角波动中位 3.5° (最大 6.8°)
 *   倾角上限就是"允许摇多大", 摇得越猛越像"剧烈抖动"。 */
#define SPD_PID_WALK_PITCH_MAX 4.0f

/* 死区内的积分衰减时间常数 (秒):
 * 误差进入死区 (|err| < 1.0 rpm) 时, 积分按 exp(-dt/tau) 衰减到 0。
 *
 * 为什么需要 (2026-10-27): 死区在 PID 之前把误差归零, 导致积分**冻结**
 * (i += 0*dt, 既不增也不减)。走路攒下的残留积分会永久留在非零值上,
 * 目标倾角恒定非零 → 车持续往前跑。积分只在换指令/摔倒/上电才清。
 *
 * 取值依据:
 *   - 控制周期 300ms (编码器 300ms 窗口), tau=3.0s ≈ 10 个周期
 *   - 残留积分要能在几秒内退干净, 但不能快到把"消除稳态误差"的能力废掉
 *   - 经验: tau < 1s 会让速度环几乎失去积分作用 (车走不直, 一直微调)
 *     tau > 10s 则退得太慢, 还是会往前跑一会儿
 */
#define SPD_PID_I_DECAY_TAU  3.0f

/* 速度环的内置默认增益 (°/rpm):
 * 参数表里的 spd_kp / spd_ki 被写成 0 时用它兜底 ——
 * 2026-10-26 的"恢复默认"事故就是旧版 App 把速度环参数写成 0,
 * 结果方向键完全没反应。这里兜底, 保证方向键永远能用
 * (参数页上把 spd_kp 拖到 0 表示"不调", 不是"关闭速度环")。
 * ⚠ 数值来自仿真: 0.06/0.01 是"速度跟得住 + 车身不乱摇"的折中点。
 *   再大 (0.15/0.05) 就会剧烈摇 (见上面的注释)。 */
#define SPD_PID_KP_DEFAULT    0.06f
#define SPD_PID_KI_DEFAULT    0.01f

/**
 * @brief 初始化速度环 (从 param 表读增益 + 清积分)
 * @note  上电初始化、参数重载时调用
 */
void speed_pid_init(void);

/**
 * @brief 从 param 表重新读取速度环增益
 * @note  **每个控制周期都调一次**: App / 网页上拖滑块后, 下一次运算立刻用新值。
 *        ⚠ 用 pid_set_gains() (只改系数, 保留积分), 不用 pid_config()。
 */
void speed_pid_load_params(void);

/**
 * @brief 清空速度环的积分与微分历史
 * @note  上电 / 摔倒恢复 / 换遥控指令 (方向变了, 旧积分要清) 时调用。
 */
void speed_pid_reset(void);

/**
 * @brief 执行一次速度环运算
 * @param dt       控制周期 (秒)
 * @param speed    实测平均轮速 (rpm, 前进为正)
 * @param target   目标平均轮速 (rpm, 前进为正)
 * @return 目标倾角 (°), 已按"输出限幅"夹过
 *
 * @note  误差 = 实测 − 目标 (前进为正)。
 *   实测比目标慢 → 误差为负 → 目标倾角为负 → 车前倾 (pitch 负 = 车头往下)
 *   → 轮子往车头跑 → 加速前进 ✓
 *   实测比目标快 → 误差为正 → 目标倾角为正 → 车后仰 → 减速 ✓
 *
 * @note  ⚠ 误差死区: 编码器量化台阶是 0.15 rpm (gear=30, 300ms 窗口),
 *   不设死区的话, 车会为了追一个量化噪声一直歪着 (慢慢往一边跑)。
 */
float speed_pid_update(float dt, float speed, float target);

#endif // SPEED_PID_H
